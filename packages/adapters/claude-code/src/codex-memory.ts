import os from "node:os";
import path from "node:path";
import { readFile } from "node:fs/promises";

/** Set to `0` to keep the Codex memory summary out of Claude Sessions. */
export const CODEX_MEMORY_ENV = "CODEXHOST_CODEX_MEMORY";

/** Skysight writes its consolidated summary here; Codex core injects the same file for GPT Threads. */
const MEMORY_SUMMARY_RELATIVE_PATH = path.join("memories", "memory_summary.md");

/** Skysight keeps the summary small; the cap only guards against a runaway file. */
const MAX_SUMMARY_BYTES = 64 * 1024;

export function codexMemorySummaryPath(environment: NodeJS.ProcessEnv): string {
  const codexHome = environment.CODEX_HOME
    ? path.resolve(environment.CODEX_HOME)
    : path.join(os.homedir(), ".codex");
  return path.join(codexHome, MEMORY_SUMMARY_RELATIVE_PATH);
}

/**
 * Reads the Codex memory summary as a system-prompt append for a Claude Session.
 *
 * Claude Threads never pass through codex-core, so its native memory injection does not
 * reach them; this is the Host-side equivalent. Returns `undefined` when the feature is
 * opted out, the file is missing, unreadable, or empty, so a Session starts without memory
 * rather than failing.
 */
export async function readCodexMemoryAppend(
  environment: NodeJS.ProcessEnv,
): Promise<string | undefined> {
  if (environment[CODEX_MEMORY_ENV]?.trim() === "0") return undefined;
  const file = codexMemorySummaryPath(environment);
  let summary: string;
  try {
    summary = (await readFile(file, "utf8")).trim();
  } catch {
    return undefined;
  }
  if (summary.length === 0) return undefined;
  if (Buffer.byteLength(summary, "utf8") > MAX_SUMMARY_BYTES) {
    summary = `${Buffer.from(summary, "utf8").subarray(0, MAX_SUMMARY_BYTES).toString("utf8")}\n[truncated]`;
  }
  return [
    `<codex-memory source="${file}">`,
    "Memory summary generated by Codex (Skysight) from past sessions across agents. Facts here are dated context: recheck anything time-sensitive before relying on it.",
    "",
    summary,
    "</codex-memory>",
  ].join("\n");
}
